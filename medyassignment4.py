import os
import numpy as np
import pandas as pd
from pathlib import Path
from scipy import stats

# -------------------- Helpers --------------------

def fit_normal(x: np.ndarray):
    mu, sigma = stats.norm.fit(x)
    return {"name": "normal", "mu": mu, "sigma": sigma}

def fit_student_t(x: np.ndarray):
    df, mu, sigma = stats.t.fit(x)   # (df, loc, scale)
    return {"name": "t", "df": df, "mu": mu, "sigma": sigma}

def model_cdf(model, x: np.ndarray):
    if model["name"] == "normal":
        return stats.norm.cdf(x, loc=model["mu"], scale=model["sigma"])
    else:
        return stats.t.cdf(x, df=model["df"], loc=model["mu"], scale=model["sigma"])

def model_ppf(model, u: np.ndarray):
    if model["name"] == "normal":
        return stats.norm.ppf(u, loc=model["mu"], scale=model["sigma"])
    else:
        return stats.t.ppf(u, df=model["df"], loc=model["mu"], scale=model["sigma"])

def gaussian_copula_pca(corr: np.ndarray, n_samples: int, rng=None):
    """Simulate Z ~ N(0, corr) using eigendecomposition (PCA)."""
    corr = np.asarray(corr)
    corr = (corr + corr.T) / 2
    evals, evecs = np.linalg.eigh(corr)
    evals = np.clip(evals, 0.0, None)
    A = evecs @ np.diag(np.sqrt(evals))
    rng = np.random.default_rng() if rng is None else rng
    z = rng.standard_normal(size=(n_samples, corr.shape[0]))
    return z @ A.T

def var_es_from_pnl(pnl: np.ndarray, alpha: float = 0.05):
    """Risk-as-positive convention: VaR = -q_alpha(PnL), ES = -E[PnL | PnL<=q]."""
    q = np.quantile(pnl, alpha)
    var = -q
    tail = pnl[pnl <= q]
    es = -np.mean(tail) if tail.size else -q
    return var, es

