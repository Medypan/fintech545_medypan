# -------------------- 9.1: fit marginals --------------------
models = {
    "A": fit_normal(cin["A"].to_numpy()),
    "B": fit_student_t(cin["B"].to_numpy()),
}

# PIT uniforms, Spearman on U
u_A = model_cdf(models["A"], cin["A"].to_numpy())
u_B = model_cdf(models["B"], cin["B"].to_numpy())
U = np.column_stack([u_A, u_B])

# Spearman via rank->Pearson（稳健且返回 2x2）
R = np.apply_along_axis(stats.rankdata, 0, U)
spcorr = np.corrcoef(R, rowvar=False)
spcorr = (spcorr + spcorr.T) / 2

# -------------------- Copula simulation (fixed seed) --------------------
nSim = 100_000
rng_sim = np.random.default_rng(20240601)  # 固定种子以稳定结果
Z = gaussian_copula_pca(spcorr, nSim, rng=rng_sim)
uSim = stats.norm.cdf(Z)

# Map back to returns
sim_A = model_ppf(models["A"], uSim[:, 0])
sim_B = model_ppf(models["B"], uSim[:, 1])
simRet = pd.DataFrame({"A": sim_A, "B": sim_B})

# -------------------- Portfolio and PnL --------------------
portfolio = pd.DataFrame({
    "Stock": ["A", "B"],
    "currentValue": [2000.0, 3000.0],
})
total_value = portfolio["currentValue"].sum()

# Long-form returns with iteration id
simRet_long = simRet.reset_index(names="iteration").melt(
    id_vars="iteration", var_name="Stock", value_name="ret"
)

# Cross-join (portfolio x iteration) and merge sim returns
iteration_df = pd.DataFrame({"iteration": np.arange(nSim, dtype=int)})
values = portfolio.merge(iteration_df, how="cross").merge(
    simRet_long, on=["iteration", "Stock"], how="left"
)
values["simulatedValue"] = values["currentValue"] * (1.0 + values["ret"])
values["pnl"] = values["simulatedValue"] - values["currentValue"]

# -------------------- Risk per stock --------------------
ALPHA = 0.05
rows = []
for stock, g in values.groupby("Stock", sort=False):
    pnl = g["pnl"].to_numpy()
    var95, es95 = var_es_from_pnl(pnl, alpha=ALPHA)
    cur_val = float(portfolio.loc[portfolio["Stock"] == stock, "currentValue"])
    rows.append({
        "Stock": stock,
        "VaR95": var95,
        "ES95": es95,
        "VaR95_Pct": var95 / cur_val,
        "ES95_Pct": es95 / cur_val,
    })

# -------------------- Total portfolio risk --------------------
pnl_total = values.pivot_table(index="iteration", values="pnl", aggfunc="sum").to_numpy().ravel()
var95_tot, es95_tot = var_es_from_pnl(pnl_total, alpha=ALPHA)
rows.append({
    "Stock": "Total",
    "VaR95": var95_tot,
    "ES95": es95_tot,
    "VaR95_Pct": var95_tot / total_value,
    "ES95_Pct": es95_tot / total_value,
})

risk = pd.DataFrame(rows, columns=["Stock", "VaR95", "ES95", "VaR95_Pct", "ES95_Pct"])
risk.to_csv(OUT_PATH, index=False)
