# ---------------------- Configuration ----------------------
ALPHA = 0.05  # left-tail probability for ES (e.g., 0.05 = 95% ES)

# ---------------------- ES Helpers ----------------------
def es_left_normal(mu: float, sigma: float, alpha: float = ALPHA) -> float:
    """
    Closed-form left-tail Expected Shortfall for Normal(mu, sigma).
    ES = E[X | X <= q_alpha] where q_alpha is the alpha-quantile.
    ES = mu - sigma * phi(z_alpha) / alpha
    """
    z_alpha = stats.norm.ppf(alpha)
    phi = stats.norm.pdf(z_alpha)
    return mu - sigma * phi / alpha

def es_left_distribution(dist, alpha: float = ALPHA) -> float:
    """
    Generic left-tail ES for a SciPy continuous distribution object (with .ppf and .expect).
    ES = (1/alpha) * ∫_{-∞}^{q_alpha} x f(x) dx
    """
    q_alpha = dist.ppf(alpha)
    # Unconditional truncated moment up to q_alpha, then divide by alpha.
    numerator = dist.expect(lb=-np.inf, ub=q_alpha)
    return numerator / alpha

def es_left_sample(x: np.ndarray, alpha: float = ALPHA) -> float:
    """
    Empirical left-tail ES from a sample x.
    ES_hat = mean of observations <= empirical alpha-quantile.
    """
    x = np.asarray(x)
    q_alpha = np.quantile(x, alpha)
    tail = x[x <= q_alpha]
    # In pathological cases (very small samples), ensure we don't divide by zero
    if tail.size == 0:
        return float(np.min(x))
    return float(np.mean(tail))

