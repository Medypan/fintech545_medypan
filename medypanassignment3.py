import numpy as np
import pandas as pd
from scipy.stats import norm, t

ALPHA = 0.05  # Use 95% VaR

def var95(x: np.ndarray) -> float:
    """VaR at 95% confidence for returns x: positive number for loss."""
    x = np.asarray(x).ravel()
    return -np.quantile(x, ALPHA)


# Test 8.1 VaR Normal

cin = pd.read_csv("test7_1.csv").to_numpy()
x = cin[:, 0].astype(float)

mu = np.mean(x)

# population (MLE) std: ddof=0 to align with MLE used in most fit routines
sigma = np.std(x, ddof=0)

# "VaR Absolute": shift by fitted mean
var_abs_norm = -norm.ppf(ALPHA, loc=mu, scale=sigma)

# "VaR Diff from Mean": zero-mean version
var_diff_norm = -norm.ppf(ALPHA, loc=0.0, scale=sigma)

pd.DataFrame({
    "VaR Absolute": [var_abs_norm],
    "VaR Diff from Mean": [var_diff_norm],
}).to_csv("medy_testout8_1.csv", index=False)


# Test 8.2 VaR TDist

cin = pd.read_csv("test7_2.csv").to_numpy()
x = cin[:, 0].astype(float)


# Fit Student-t: returns df, loc (mean-ish), scale (sigma-ish)

# Using MLE; this matches with the fit_general_t
df_hat, loc_hat, scale_hat = t.fit(x)

# "VaR Absolute": with fitted loc & scale
var_abs_t = -t.ppf(ALPHA, df_hat, loc=loc_hat, scale=scale_hat)

# "VaR Diff from Mean": zero-mean but same df & scale
var_diff_t = -t.ppf(ALPHA, df_hat, loc=0.0, scale=scale_hat)

pd.DataFrame({
    "VaR Absolute": [var_abs_t],
    "VaR Diff from Mean": [var_diff_t],
}).to_csv("medy_testout8_2.csv", index=False)



