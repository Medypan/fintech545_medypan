import numpy as np
import pandas as pd


def symmetrize(A):
    return (A + A.T) / 2.0

def eig_clip_psd(A, eps=0.0):
    """Symmetric eigenvalue clipping."""
    A = symmetrize(A)
    vals, vecs = np.linalg.eigh(A)
    vals_clipped = np.maximum(vals, eps)
    return (vecs * vals_clipped) @ vecs.T

def near_psd_cov(S, eps=0.0):
    """Near-PSD repair for covariance matrices."""
    S2 = eig_clip_psd(S, eps=eps)
    d_old = np.sqrt(np.clip(np.diag(S), 1e-16, None))
    d_new = np.sqrt(np.clip(np.diag(S2), 1e-16, None))
    T = np.diag(d_old / d_new)
    S_new = T @ S2 @ T
    return symmetrize(S_new)

def higham_corr(A, max_iter=100, tol=1e-10):
    """Higham nearest correlation matrix."""
    A = symmetrize(np.array(A, dtype=float))
    Y = A.copy()
    deltaS = np.zeros_like(A)

    for _ in range(max_iter):
        R = Y - deltaS
        R_psd = eig_clip_psd(R, eps=0.0)
        deltaS = R_psd - R
        Y = R_psd.copy()
        np.fill_diagonal(Y, 1.0)

        if np.linalg.norm(Y - R_psd) < tol:
            break

    Y = symmetrize(Y)
    np.fill_diagonal(Y, 1.0)
    return Y

def higham_cov(S, max_iter=100, tol=1e-10):
    """Higham nearest covariance matrix."""
    S = symmetrize(np.array(S, dtype=float))
    std = np.sqrt(np.clip(np.diag(S), 1e-16, None))
    D = np.diag(std)
    Dinv = np.diag(1.0 / std)
    R = Dinv @ S @ Dinv
    Rn = higham_corr(R, max_iter=max_iter, tol=tol)
    Sn = D @ Rn @ D
    return symmetrize(Sn)

# Simulators

def simulate_normal(n, cov, fixMethod=None):
    """Normal simulation with optional PSD fixes."""
    cov = np.array(cov)
    if fixMethod == "near_psd":
        cov = near_psd_cov(cov)
    elif fixMethod == "higham":
        cov = higham_cov(cov)
    mean = np.zeros(cov.shape[0])
    return np.random.multivariate_normal(mean, cov, size=n)

def simulate_pca(cov, n, pctExp=0.99):
    """PCA-based simulation keeping enough PCs to explain pctExp variance."""
    eigvals, eigvecs = np.linalg.eigh(cov)
    idx = np.argsort(eigvals)[::-1]
    eigvals, eigvecs = eigvals[idx], eigvecs[:, idx]
    cumvar = np.cumsum(eigvals) / np.sum(eigvals)
    k = np.searchsorted(cumvar, pctExp) + 1
    L = eigvecs[:, :k] @ np.diag(np.sqrt(eigvals[:k]))
    Z = np.random.randn(n, k)
    return Z @ L.T

def sample_cov(X):
    """Return sample covariance with variables in columns."""
    return np.cov(X, rowvar=False, bias=False)


